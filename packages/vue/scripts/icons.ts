// Select the names in src/icons/names.ts from @iconify-json/lucide and write src/icons/lucide.ts; commit the output.
// `--check` writes nothing and fails when the committed file is stale (CI runs it through `pnpm check`).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { getIcons } from '@iconify/utils';
import type { IconifyJSON } from '@iconify/types';
import { BUNDLED_ICONS } from '../src/icons/names.ts';

const check = process.argv.includes('--check');
const require = createRequire(import.meta.url);
const source = JSON.parse(readFileSync(require.resolve('@iconify-json/lucide/icons.json'), 'utf8')) as IconifyJSON;
const subset = getIcons(source, [...BUNDLED_ICONS], true);
if (!subset) throw new Error('Cannot extract a subset from the Lucide icon set');

const missing = BUNDLED_ICONS.filter(name => !subset.icons[name] && !subset.aliases?.[name]);
if (missing.length) throw new Error(`Icons missing from Lucide: ${missing.join(', ')}`);

// Keep only rendering fields, so metadata such as lastModified never produces a meaningless diff.
const { prefix, icons, aliases, width, height } = subset;
const data = { prefix, icons, ...(aliases && Object.keys(aliases).length ? { aliases } : {}), width, height };

const content = `/*
 * Generated by packages/vue/scripts/icons.ts from @iconify-json/lucide; do not edit. After changing
 * src/icons/names.ts, run \`pnpm --filter @opennavo/design-vue gen\`.
 *
 * Icon data: Lucide (https://lucide.dev), ISC License, with portions derived from Feather (MIT License).
 * The license texts are in packages/vue/THIRD_PARTY_NOTICES.md.
 */
import type { OnIconSet } from './set';

export const lucideSubset: OnIconSet = ${JSON.stringify(data, null, 2)};
`;

const target = fileURLToPath(new URL('../src/icons/lucide.ts', import.meta.url));
if (check) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== content) {
    console.error('src/icons/lucide.ts is out of date; run pnpm --filter @opennavo/design-vue gen');
    process.exit(1);
  }
  console.log(`src/icons/lucide.ts is up to date (${Object.keys(icons).length} icons)`);
} else {
  writeFileSync(target, content);
  console.log(`src/icons/lucide.ts: ${Object.keys(icons).length} icons`);
}
